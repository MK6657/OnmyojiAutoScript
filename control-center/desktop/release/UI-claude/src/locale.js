const normalizeKey = (value) => String(value || '').trim()
  .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
  .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
  .toLowerCase()
  .replace(/[-\s]+/g, '_')
const canonicalKey = (value) => normalizeKey(value).replace(/_/g, '')

const compactMap = (source) => Object.fromEntries(Object.entries(source).map(([key, value]) => [canonicalKey(key), value]))
